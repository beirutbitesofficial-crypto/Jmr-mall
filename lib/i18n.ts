const serverPatterns: [RegExp, (...parts: string[]) => string][] = [
  [/^الشهر التالي لازم يكون (\S+)$/, month => `The next month must be ${month}`],
  [/^اعتمد شهر (\S+) قبل استيراد شهر جديد$/, month => `Approve ${month} before importing a new month`],
  [/^الاستيراد متاح لآخر شهر \((\S+)\) فقط\. الأشهر السابقة أرشيف ثابت\.$/, month => `Imports are only allowed into the latest month (${month}). Earlier months are a fixed archive.`],
  [/^تم استيراد (\d+) سجل لشهر (\S+)$/, (count, month) => `Imported ${count} records for ${month}`],
  [/^تم تجاهل الشيت (.+): ما لقينا عمود واضح لرقم العداد\/القسم\.$/, sheet => `Skipped sheet ${sheet}: no clear meter / shop column.`],
  [/^تكرار (.+) في (.+); اعتمدنا السطر الأكثر اكتمالاً\.$/, (name, sheet) => `${name} repeats in ${sheet}; kept the most complete row.`],
  [/^(.+): تم تجاهل (.+) السالب \((.+)\)\.$/, (where, field, value) => `${where}: ignored negative ${translateMessage(field, "en")} (${value}).`],
];

export function translateMessage(message: string, lang: Lang): string {
  if (lang === "ar") return message;
  if (serverMessages[message]) return serverMessages[message];
  for (const [pattern, render] of serverPatterns) {
    const match = message.match(pattern);
    if (match) return render(...match.slice(1));
  }
  return message;
}
